// dotnet/tools/JsTimeline.SchemaGen/ModelEmitter.cs
namespace JsTimeline.SchemaGen;

/// <summary>Writes the C# source of the <see cref="TypeModel"/>s read from the schema.</summary>
internal static class ModelEmitter
{
    private const string WhenWritingNull =
        "[JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]";

    public static string Emit(IReadOnlyList<TypeModel> types, string ns, string sourceName)
    {
        var w = new CodeWriter();
        w.Line("// <auto-generated>")
            .Line($"// Generated by JsTimeline.SchemaGen from {sourceName}.")
            .Line("// Do not edit: the build regenerates this file when the schema changes.")
            .Line("// </auto-generated>")
            .Line("#nullable enable")
            .Line("#pragma warning disable CS1591 // A schema entry without a description has no doc comment.")
            .Line()
            .Line($"namespace {ns};")
            .Line()
            .Line("using System;")
            .Line("using System.Collections.Generic;")
            .Line("using System.Text.Json;")
            .Line("using System.Text.Json.Serialization;");
        foreach (var type in types)
        {
            w.Line();
            switch (type)
            {
                case ObjectModel model:
                    EmitObject(w, model);
                    break;
                case EnumModel model:
                    EmitEnum(w, model);
                    break;
                case UnionModel model:
                    EmitUnion(w, model);
                    break;
                case FlatUnionModel model:
                    EmitFlatUnion(w, model);
                    break;
            }
        }
        return w.ToString();
    }

    private static void EmitObject(CodeWriter w, ObjectModel model)
    {
        w.Summary(model.Description);
        if (model.Closed)
        {
            w.Line("[JsonUnmappedMemberHandling(JsonUnmappedMemberHandling.Disallow)]");
        }
        var bases = model.BaseName is null ? "IJsonOnDeserialized" : $"{model.BaseName}, IJsonOnDeserialized";
        w.Open($"public sealed record {model.Name} : {bases}");
        EmitProperties(w, model.Properties);
        w.Line();
        EmitRequiredCheck(w, model);
        w.Close();
    }

    /// <summary>
    /// System.Text.Json (net8) checks that a required key is present, not that its value is non-null:
    /// refuse <c>"id": null</c> here so a non-nullable property is never null after reading.
    /// </summary>
    private static void EmitRequiredCheck(CodeWriter w, ObjectModel model)
    {
        var checkedProperties = model.Properties.Where(p => p.Required && !p.IsValueType && p.ConstValue is null).ToList();
        if (checkedProperties.Count == 0)
        {
            w.Line("void IJsonOnDeserialized.OnDeserialized()").Line("{").Line("}");
            return;
        }
        w.Open("void IJsonOnDeserialized.OnDeserialized()");
        foreach (var p in checkedProperties)
        {
            w.Line($"if ({p.ClrName} is null)").Line("{")
                .Line($"    throw new JsonException(\"{model.Name}: \\\"{Naming.Literal(p.JsonName)}\\\" cannot be null.\");").Line("}");
        }
        w.Close();
    }

    private static void EmitProperties(CodeWriter w, IReadOnlyList<PropertyModel> properties)
    {
        for (var i = 0; i < properties.Count; i++)
        {
            if (i > 0)
            {
                w.Line();
            }
            EmitProperty(w, properties[i]);
        }
    }

    private static void EmitProperty(CodeWriter w, PropertyModel p)
    {
        w.Summary(p.Description);
        if (p.DefaultText is not null)
        {
            w.Line($"/// <remarks>Default when absent: <c>{Naming.Xml(p.DefaultText)}</c>.</remarks>");
        }
        w.Line($"[JsonPropertyName(\"{Naming.Literal(p.JsonName)}\")]");
        if (p.ConstValue is not null)
        {
            w.Line($"public string {p.ClrName} => \"{Naming.Literal(p.ConstValue)}\";");
            return;
        }
        if (p.Required)
        {
            w.Line($"public required {p.ClrType} {p.ClrName} {{ get; init; }}");
            return;
        }
        w.Line(WhenWritingNull);
        w.Line($"public {p.ClrType}? {p.ClrName} {{ get; init; }}");
    }

    private static void EmitEnum(CodeWriter w, EnumModel model)
    {
        var converter = model.Name + "JsonConverter";
        w.Summary(model.Description);
        w.Line($"[JsonConverter(typeof({converter}))]");
        w.Open($"public enum {model.Name}");
        foreach (var value in model.Values)
        {
            w.Line($"/// <summary><c>\"{Naming.Xml(value)}\"</c></summary>");
            w.Line(Naming.Pascal(value) + ",");
        }
        w.Close();
        w.Line();
        w.Line($"/// <summary>Reads and writes <see cref=\"{model.Name}\"/> as its exact schema string.</summary>");
        w.Open($"internal sealed class {converter} : JsonConverter<{model.Name}>");
        w.Open($"public override {model.Name} Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)");
        w.Line("if (reader.TokenType != JsonTokenType.String)")
            .Line("{")
            .Line($"    throw new JsonException(\"{model.Name} must be a JSON string.\");")
            .Line("}");
        w.Open("return reader.GetString() switch");
        foreach (var value in model.Values)
        {
            w.Line($"\"{Naming.Literal(value)}\" => {model.Name}.{Naming.Pascal(value)},");
        }
        w.Line($"var other => throw new JsonException($\"\\\"{{other}}\\\" is not a valid {model.Name}.\"),");
        w.Close(";");
        w.Close();
        w.Line();
        w.Line($"public override void Write(Utf8JsonWriter writer, {model.Name} value, JsonSerializerOptions options) =>");
        w.Line("    writer.WriteStringValue(value switch");
        w.Line("    {");
        foreach (var value in model.Values)
        {
            w.Line($"        {model.Name}.{Naming.Pascal(value)} => \"{Naming.Literal(value)}\",");
        }
        w.Line($"        _ => throw new JsonException($\"{{value}} is not a valid {model.Name}.\"),");
        w.Line("    });");
        w.Close();
    }

    private static void EmitUnion(CodeWriter w, UnionModel model)
    {
        var converter = model.Name + "JsonConverter";
        var discriminator = Naming.Literal(model.DiscriminatorJsonName);
        w.Summary(model.Description);
        w.Line($"[JsonConverter(typeof({converter}))]");
        w.Open($"public abstract record {model.Name}");
        w.Summary("Only the generated variants derive from this type.");
        w.Line($"private protected {model.Name}()").Line("{").Line("}");
        w.Close();
        w.Line();
        w.Line($"/// <summary>Picks the variant of <see cref=\"{model.Name}\"/> from \"{discriminator}\", wherever it is in the object.</summary>");
        w.Open($"internal sealed class {converter} : JsonConverter<{model.Name}>");
        w.Line("public override bool HandleNull => true;");
        w.Line();
        w.Open($"public override {model.Name} Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)");
        w.Line("using var document = JsonDocument.ParseValue(ref reader);");
        w.Line("var root = document.RootElement;");
        w.Line("if (root.ValueKind != JsonValueKind.Object");
        w.Line($"    || !root.TryGetProperty(\"{discriminator}\", out var discriminator)");
        w.Line("    || discriminator.ValueKind != JsonValueKind.String)");
        w.Line("{");
        w.Line($"    throw new JsonException(\"A {model.Name} must be an object with a string \\\"{discriminator}\\\".\");");
        w.Line("}");
        w.Open($"{model.Name}? node = discriminator.GetString() switch");
        foreach (var variant in model.Variants)
        {
            w.Line($"\"{Naming.Literal(variant.DiscriminatorValue)}\" => root.Deserialize<{variant.TypeName}>(options),");
        }
        w.Line($"var other => throw new JsonException($\"\\\"{{other}}\\\" is not a known {model.Name} {discriminator}.\"),");
        w.Close(";");
        w.Line($"return node ?? throw new JsonException(\"A {model.Name} cannot be null.\");");
        w.Close();
        w.Line();
        w.Open($"public override void Write(Utf8JsonWriter writer, {model.Name} value, JsonSerializerOptions options)");
        w.Line("if (value is null)")
            .Line("{")
            .Line($"    throw new JsonException(\"A {model.Name} cannot be null.\");")
            .Line("}");
        w.Line("JsonSerializer.Serialize(writer, value, value.GetType(), options);");
        w.Close();
        w.Close();
    }

    private static void EmitFlatUnion(CodeWriter w, FlatUnionModel model)
    {
        w.Summary(model.Description);
        w.Line("/// <remarks>");
        w.Line("/// The JSON forms are told apart by their key: exactly one form must be set. The rule is checked");
        w.Line("/// when the object is read or written as JSON and by the <c>From...</c> factories.");
        w.Line("/// </remarks>");
        w.Line("[JsonUnmappedMemberHandling(JsonUnmappedMemberHandling.Disallow)]");
        w.Open($"public sealed record {model.Name} : IJsonOnDeserialized, IJsonOnSerializing");
        EmitProperties(w, model.Properties);
        foreach (var variant in model.Variants)
        {
            w.Line();
            EmitFactory(w, model, variant);
        }
        w.Line();
        EmitValidation(w, model);
        w.Line();
        w.Line("void IJsonOnDeserialized.OnDeserialized() => ThrowIfInvalid();");
        w.Line();
        w.Line("void IJsonOnSerializing.OnSerializing() => ThrowIfInvalid();");
        w.Line();
        w.Open("private void ThrowIfInvalid()");
        w.Line("var error = GetValidationError();");
        w.Line("if (error is not null)").Line("{").Line("    throw new JsonException(error);").Line("}");
        w.Close();
        w.Close();
    }

    private static void EmitFactory(CodeWriter w, FlatUnionModel model, FlatVariant variant)
    {
        var byName = model.Properties.ToDictionary(p => p.JsonName, StringComparer.Ordinal);
        var ordered = variant.RequiredJsonNames
            .Concat(variant.AllowedJsonNames.Where(n => !variant.RequiredJsonNames.Contains(n)))
            .Select(n => byName[n])
            .ToList();
        var parameters = ordered.Select(p => variant.RequiredJsonNames.Contains(p.JsonName)
            ? $"{p.ClrType} {Naming.Parameter(p.JsonName)}"
            : $"{p.ClrType}? {Naming.Parameter(p.JsonName)} = null");
        var assignments = ordered.Select(p => $"{p.ClrName} = {Naming.Parameter(p.JsonName)}");
        var keys = string.Join(", ", variant.RequiredJsonNames.Select(n => $"\"{n}\""));
        w.Line($"/// <summary>Creates the {Naming.Xml(keys)} form.</summary>");
        w.Line($"/// <exception cref=\"ArgumentException\">The values break a rule of the form.</exception>");
        w.Open($"public static {model.Name} {variant.FactoryName}({string.Join(", ", parameters)})");
        w.Line($"var value = new {model.Name} {{ {string.Join(", ", assignments)} }};");
        w.Line("var error = value.GetValidationError();");
        w.Line("return error is null ? value : throw new ArgumentException(error);");
        w.Close();
    }

    private static void EmitValidation(CodeWriter w, FlatUnionModel model)
    {
        var byName = model.Properties.ToDictionary(p => p.JsonName, StringComparer.Ordinal);
        var flags = model.Variants.Select(v => "is" + v.FactoryName["From".Length..]).ToList();
        w.Summary("Returns why this value breaks the exactly-one rule or a length rule, or null when it is valid.");
        w.Open("public string? GetValidationError()");
        for (var i = 0; i < model.Variants.Count; i++)
        {
            var condition = string.Join(" && ", model.Variants[i].RequiredJsonNames.Select(n => $"{byName[n].ClrName} is not null"));
            w.Line($"var {flags[i]} = {condition};");
        }
        var count = string.Join(" + ", flags.Select(f => $"({f} ? 1 : 0)"));
        var keys = string.Join(", ", model.Variants.Select(v => string.Join(" + ", v.RequiredJsonNames.Select(n => $"\\\"{n}\\\""))));
        w.Line($"if ({count} != 1)").Line("{")
            .Line($"    return \"{model.Name} needs exactly one of {keys}.\";").Line("}");
        for (var i = 0; i < model.Variants.Count; i++)
        {
            var variant = model.Variants[i];
            var form = string.Join(" + ", variant.RequiredJsonNames.Select(n => $"\\\"{n}\\\""));
            // Keys of another form are already covered by the exactly-one check.
            var extras = model.Properties.Where(p => !variant.AllowedJsonNames.Contains(p.JsonName)
                && !model.Variants.Any(v => v.RequiredJsonNames.Contains(p.JsonName)));
            foreach (var p in extras)
            {
                w.Line($"if ({flags[i]} && {p.ClrName} is not null)").Line("{")
                    .Line($"    return \"{model.Name}: \\\"{p.JsonName}\\\" is not allowed with {form}.\";").Line("}");
            }
        }
        foreach (var p in model.Properties.Where(p => p.MinLength is > 0 && p.ClrType == "string"))
        {
            w.Line($"if ({p.ClrName} is {{ Length: < {p.MinLength} }})").Line("{")
                .Line($"    return \"{model.Name}: \\\"{p.JsonName}\\\" needs at least {p.MinLength} character(s).\";").Line("}");
        }
        w.Line("return null;");
        w.Close();
    }
}
